// Package gen turns a resolved domain graph into compiler-owned source files.
//
// Everything it emits lives under internal/forge_generated/** and is wholly
// owned by Forge (ADR-001 §16): it may be deleted and recreated at will, and
// direct edits are lost. Generated code is an ordinary consumer of Gombit's
// public packages and never duplicates Gombit infrastructure (ADR-004 D3).
//
// Output is deterministic. The same compiler version and the same spec
// produce byte-identical files: iteration follows the graph's authored order,
// no map ranges reach ordered output, and nothing time- or random-dependent
// is emitted (DESIGN.md §9, §32).
package gen

import (
	"fmt"
	"go/format"
	"path"
	"strings"

	"github.com/gombit-dev/gombit-forge/internal/compiler/graph"
)

// GeneratedRoot is the compiler-owned directory every backend file lives
// under (ADR-001 §15).
const GeneratedRoot = "internal/forge_generated"

// ExtensionsRoot is the user-owned code directory (ADR-001 §17). Forge compiles
// it and references it from generated wiring, and may create a one-time stub
// under it, but never rewrites a user implementation. The generated tree
// (GeneratedRoot) and this tree never share ownership (D7).
const ExtensionsRoot = "internal/extensions"

// ExtensionPackageDir is the user-owned package directory for one resource's
// hand-written extension code, e.g. "internal/extensions/customer". Its package
// name matches the generated package (PackageName), so a stub imports the
// generated package under an alias.
func ExtensionPackageDir(resource *graph.Resource) string {
	return path.Join(ExtensionsRoot, PackageName(resource))
}

// ExtensionPackageDirForCodeName is ExtensionPackageDir keyed by a resource's
// frozen code name rather than a graph node, for callers that no longer hold the
// resource in a built graph — extension archival (ADR-001 §46) runs after a
// resource has been deleted from the spec, so it has only the code name recorded
// before deletion. It folds the name through the same rule as PackageName, so
// the archived directory matches the one the stub generator wrote.
func ExtensionPackageDirForCodeName(codeName string) string {
	return path.Join(ExtensionsRoot, packageNameForCodeName(codeName))
}

// Banner marks a file as compiler-owned. It is the first line of every
// generated Go file so a reader and any tooling know edits will be lost
// (ADR-001 §16).
const Banner = "// Code generated by Gombit Forge. DO NOT EDIT."

// File is one generated source file, addressed by its repo-relative path.
type File struct {
	// Path is slash-separated and relative to the module root.
	Path string
	// Content is the exact bytes to write.
	Content []byte
}

// PackageDir is the compiler-owned directory for one resource,
// e.g. "internal/forge_generated/customer".
func PackageDir(resource *graph.Resource) string {
	return path.Join(GeneratedRoot, PackageName(resource))
}

// PackageName is the Go package name for a resource's generated code.
//
// It is the lowercased frozen code symbol. Deriving it from the frozen symbol
// rather than the label keeps the package name stable across relabels. The
// fold can still produce an illegal package name (a Go keyword, or "main") or
// collide with another resource's fold; validatePackages rejects all of those
// before any source is emitted.
func PackageName(resource *graph.Resource) string {
	return packageNameForCodeName(resource.CodeName())
}

// packageNameForCodeName is the fold from a frozen code symbol to its Go package
// name — the single source of truth PackageName and ExtensionPackageDirForCodeName
// share, so a resource's package name is identical whether derived from a graph
// node or from a bare code name.
func packageNameForCodeName(codeName string) string {
	return strings.ToLower(codeName)
}

// The field/accessor-namespace reservations — the gorm.Model promoted fields
// and the generated model methods (TableName) a field code_name may not
// collide with — live in spec.reservedModelSymbols (F0 #19), which both this
// generator and the validator consult so the two cannot disagree. A stage that
// adds a model field or method extends that table, not a copy here. The
// reservations below are the generation-specific ones this package owns: they
// depend on how it lays out packages and imports, not on the framework model.

// reservedPackageSymbols are exported package-level identifiers the generated
// code defines in every resource package besides the model type itself: the
// handler type and the route entry point. A resource whose code symbol is one
// of these would redeclare it — model `type Handler` clashing with the handler
// struct, or `type Register` with the Register func — so the code symbol is
// rejected here rather than by go build (ADR-001 §12). Later stages that add
// package-level symbols extend this set.
var reservedPackageSymbols = map[string]struct{}{
	"Handler":       {},
	"Register":      {},
	"RegisterAdmin": {},
}

// packageLevelSymbols returns every exported package-level identifier the
// generated resource package defines, mapped to a description of what defines
// it. It is the single reservation set a stage that mints a *derived*
// package-level identifier (one built from the resource's code symbol, which
// reservedPackageSymbols' fixed names do not cover) checks its candidates
// against, so two stages cannot mint colliding symbols and have the clash
// surface at go build (ADR-001 §12, §36: reserve, don't discover).
//
// A stage that adds a package-level symbol to the resource package must extend
// this set. Today: the model type <Code>, the extension-view interface
// <Code>View and its constructor New<Code>View, the before-hook mutation types
// <Code>CreateDraft and <Code>UpdateChanges, plus the fixed handler and
// registration funcs.
func packageLevelSymbols(resource *graph.Resource) map[string]string {
	code := resource.CodeName()
	symbols := map[string]string{
		code:                   "the generated model type",
		code + "View":          "the generated extension-view interface",
		"New" + code + "View":  "the generated extension-view constructor",
		code + "CreateDraft":   "the generated before-create draft type",
		code + "UpdateChanges": "the generated before-update change-set type",
	}
	// The hook contract is emitted only for a resource that declares hooks, so
	// its symbols are reserved only then — reserving them unconditionally would
	// reject a field reference against a type that this resource never emits.
	if len(resource.Spec.Hooks) > 0 {
		symbols[code+"Hooks"] = "the generated hook contract interface"
		symbols["Register"+code+"Hooks"] = "the generated hook registration func"
		symbols[code+"HookImpl"] = "the generated hook accessor"
	}
	for name := range reservedPackageSymbols {
		symbols[name] = "a generated handler/registration symbol"
	}
	return symbols
}

// reservedPackageNames are names the go tool treats specially, so a resource
// may not fold to one. Our fold is both the directory basename and the package
// clause, so this is the union of both go/build rules — derived from go/build,
// not accumulated from examples:
//
//	main           needs a func main and cannot be imported (package clause)
//	documentation  go/build adds .go files in `package documentation` to
//	               IgnoredGoFiles, so the model would be dropped (package clause)
//	internal       an import-boundary directory; cmd/ could not import the model
//	testdata       a directory go/build ignores, so the compile gate never sees it
//
// go/build's only special package clause is "documentation" (build.go: the
// sole `pkg == "..."` check when collecting files); its only ignored directory
// forms are "testdata" and names beginning "." or "_". A fold of an exported
// identifier cannot begin "." or "_", and "vendor" is an ordinary package in
// module mode (verified against the go tool), so neither is reserved. Go
// keywords are rejected separately as invalid identifiers.
var reservedPackageNames = map[string]string{
	"main":          "a package that needs a func main and cannot be imported",
	"documentation": "a package clause the go tool ignores, so the generated model would be dropped from the build",
	"internal":      "an internal-import-boundary directory the application shell could not import",
	"testdata":      "a directory the go tool ignores, so the generated model would be invisible to the build",
}

// reservedImportPackages are the base names of the third-party packages the
// generated code imports as bare identifiers (framework, contract, database,
// admin, gorm, huma, decimal). A resource folding to one of these would put two
// imports with the same local name in one file — the generated package plus the
// import it uses — which does not compile ("X redeclared in this block"). This
// closes the whole class rather than one example.
var reservedImportPackages = map[string]struct{}{
	"framework": {}, "contract": {}, "database": {}, "admin": {},
	"gorm": {}, "huma": {}, "decimal": {},
}

// formatGo runs gofmt over generated Go source.
//
// Formatting is part of the determinism contract, and it doubles as a
// correctness gate: malformed generated source fails here with the offending
// file named, rather than at the caller's build.
func formatGo(relPath string, src string) (File, error) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return File{}, fmt.Errorf("gen: format %s: %w", relPath, err)
	}
	return File{Path: relPath, Content: formatted}, nil
}
